function studyhub_st( $key ) {
	$d = studyhub_site_dict();
	if ( ! isset( $d[ $key ] ) ) {
		return $key;
	}
	return 'kk' === studyhub_lang() && ! empty( $d[ $key ][1] ) ? $d[ $key ][1] : $d[ $key ][0];
}
